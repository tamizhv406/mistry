/**
 * Draws every PNG icon and splash screen from the logo in src/config/brand.ts, using headless
 * Chrome. Only needed when the logo or its colours change (the icons carry no app name, so a
 * rename does not need it).
 *
 *   npm i -D puppeteer-core        (once, or point PUPPETEER_CORE at an installed copy)
 *   npx tsx scripts/generate-brand-icons.ts
 *
 * Chrome is looked for at CHROME_PATH, else the usual Windows / macOS / Linux location.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BRAND_COLORS, LOGO_MARK, logoSvg } from '../src/config/brand';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = (p: string) => path.join(root, p);
const res = 'android/app/src/main/res';

const chromePath = process.env.CHROME_PATH || [
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].find(p => fs.existsSync(p));
if (!chromePath) throw new Error('Chrome not found: set CHROME_PATH.');

const modulePath = process.env.PUPPETEER_CORE;
const { default: puppeteer } = await import(modulePath ? pathToFileURL(modulePath).href : 'puppeteer-core');
const browser = await puppeteer.launch({ executablePath: chromePath, headless: true });
const page = await browser.newPage();

/** Renders an SVG (or a centred logo on a coloured page, for splash screens) to a PNG file. */
async function render(file: string, w: number, h: number, svg: string, background = 'transparent') {
  await page.setViewport({ width: w, height: h, deviceScaleFactor: 1 });
  await page.setContent(
    `<html><body style="margin:0;width:${w}px;height:${h}px;display:flex;align-items:center;justify-content:center;background:${background}">${svg}</body></html>`,
  );
  fs.mkdirSync(path.dirname(out(file)), { recursive: true });
  await page.screenshot({ path: out(file), clip: { x: 0, y: 0, width: w, height: h }, omitBackground: background === 'transparent' });
  console.log(`  ${file} (${w}×${h})`);
}

// Web / PWA. The maskable icon keeps the mark inside the 80% safe circle.
await render('public/icons/icon-192.png', 192, 192, logoSvg({ size: 192 }));
await render('public/icons/icon-512.png', 512, 512, logoSvg({ size: 512 }));
await render('public/icons/icon-maskable.png', 512, 512, logoSvg({ size: 512, shape: 'square', markScale: 0.78 }));

// Android launcher icons: legacy square + round, and the adaptive-icon foreground (mark inside
// the 66/108 safe zone; the background colour comes from values/ic_launcher_background.xml).
const densities: Record<string, number> = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [d, k] of Object.entries(densities)) {
  const icon = Math.round(48 * k);
  const fg = Math.round(108 * k);
  await render(`${res}/mipmap-${d}/ic_launcher.png`, icon, icon, logoSvg({ size: icon }));
  await render(`${res}/mipmap-${d}/ic_launcher_round.png`, icon, icon, logoSvg({ size: icon, shape: 'circle', markScale: 0.9 }));
  await render(`${res}/mipmap-${d}/ic_launcher_foreground.png`, fg, fg, logoSvg({ size: fg, shape: 'none', markScale: 0.64 }));
}

// Splash screens: the logo tile centred on the app background.
const splash: Array<[string, number, number]> = [
  ['drawable', 480, 320],
  ['drawable-land-mdpi', 480, 320], ['drawable-land-hdpi', 800, 480], ['drawable-land-xhdpi', 1280, 720],
  ['drawable-land-xxhdpi', 1600, 960], ['drawable-land-xxxhdpi', 1920, 1280],
  ['drawable-port-mdpi', 320, 480], ['drawable-port-hdpi', 480, 800], ['drawable-port-xhdpi', 720, 1280],
  ['drawable-port-xxhdpi', 960, 1600], ['drawable-port-xxxhdpi', 1280, 1920],
];
for (const [dir, w, h] of splash) {
  await render(`${res}/${dir}/splash.png`, w, h, logoSvg({ size: Math.round(Math.min(w, h) * 0.3) }), BRAND_COLORS.background);
}
await browser.close();

// Android vector versions (used where the system prefers a drawable over the PNGs).
const v = 108;
const k = (v / LOGO_MARK.viewBox) * 0.64;
const off = (v - LOGO_MARK.viewBox * k) / 2;
const toPath = (pts: string) => 'M' + pts.split(' ').join(' L');
fs.writeFileSync(out(`${res}/drawable-v24/ic_launcher_foreground.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-brand-icons.ts from src/config/brand.ts -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="${off.toFixed(3)}" android:translateY="${off.toFixed(3)}" android:scaleX="${k.toFixed(4)}" android:scaleY="${k.toFixed(4)}">
        <path android:pathData="${toPath(LOGO_MARK.roof.points)}" android:strokeColor="${BRAND_COLORS.primary}" android:strokeWidth="${LOGO_MARK.roof.width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />
        <path android:pathData="${toPath(LOGO_MARK.letter.points)}" android:strokeColor="${LOGO_MARK.letter.color}" android:strokeWidth="${LOGO_MARK.letter.width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />
    </group>
</vector>
`);
fs.writeFileSync(out(`${res}/drawable/ic_launcher_background.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-brand-icons.ts from src/config/brand.ts -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="${BRAND_COLORS.dark}" android:pathData="M0,0h108v108h-108z" />
</vector>
`);
console.log('  Android vector foreground + background');
